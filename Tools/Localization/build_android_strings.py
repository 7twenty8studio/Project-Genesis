#!/usr/bin/env python3
"""Writes the Android app's string resources from the same translations iOS uses.

  python3 Tools/Localization/build_android_strings.py          # write
  python3 Tools/Localization/build_android_strings.py --check  # fail if stale

android_strings.json names each Android resource and its English text, written
exactly as the iOS app writes it. The Spanish and Brazilian Portuguese come
from es.json and pt.json (English key -> translation), so a word is translated
once for both apps. Writes android/app/src/main/res/values{,-es,-pt-rBR}/strings.xml.

Fails, listing them, if a string has no translation or a translation's
placeholders don't match the English. iOS placeholders become Android ones:
%@ -> %s, %lld/%d -> %d, numbered (%1$s) when a string has more than one.
"""
import json
import os
import re
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RES = os.path.join(ROOT, "android/app/src/main/res")
LANGUAGES = {"": None, "-es": "es.json", "-pt-rBR": "pt.json"}
SPECIFIER = re.compile(r"%(\d+\$)?(@|lld|ld|d|f|lf)")
KINDS = {"@": "s", "lld": "d", "ld": "d", "d": "d", "f": "f", "lf": "f"}


def specifiers(text):
    return sorted((m.group(1) or "", KINDS[m.group(2)]) for m in SPECIFIER.finditer(text))


def android_format(text):
    found = list(SPECIFIER.finditer(text))
    numbered = len(found) > 1
    counter = iter(range(1, len(found) + 1))

    def replace(match):
        position = match.group(1)[:-1] if match.group(1) else str(next(counter))
        kind = KINDS[match.group(2)]
        return f"%{position}${kind}" if numbered else f"%{kind}"

    out = SPECIFIER.sub(replace, text)
    # Android reads ' and " specially in resources.
    return escape(out).replace("'", "\\'").replace('"', '\\"')


def build():
    with open(os.path.join(HERE, "android_strings.json"), encoding="utf-8") as f:
        names = json.load(f)["strings"]
    files, problems = {}, []
    for suffix, source in LANGUAGES.items():
        table = {}
        if source:
            with open(os.path.join(HERE, source), encoding="utf-8") as f:
                table = json.load(f)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by Tools/Localization/build_android_strings.py. Don't edit. -->",
                 "<resources>"]
        for name, english in names.items():
            text = english if not source else table.get(english)
            if text is None:
                problems.append(f"{source}: no translation for {english!r} ({name})")
                continue
            if sorted(k for _, k in specifiers(text)) != sorted(k for _, k in specifiers(english)):
                problems.append(f"{source}: placeholders differ for {english!r}")
                continue
            if name == "app_name" and source:
                continue  # The brand is never translated.
            lines.append(f'    <string name="{name}">{android_format(text)}</string>')
        lines.append("</resources>")
        files[os.path.join(RES, f"values{suffix}", "strings.xml")] = "\n".join(lines) + "\n"
    return files, problems


def main():
    files, problems = build()
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    check = "--check" in sys.argv
    stale = []
    for path, content in files.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != content:
            if check:
                stale.append(os.path.relpath(path, ROOT))
            else:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
    if stale:
        print("Stale; run python3 Tools/Localization/build_android_strings.py:\n" + "\n".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()

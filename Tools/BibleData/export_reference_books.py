#!/usr/bin/env python3
"""Writes supabase/functions/_shared/bibleBooks.json for the TypeScript
reference parser (supabase/functions/_shared/references.ts), used by Church
Studio and the guest sermon page (VRS-18).

Everything comes from the app, so the web reads references exactly as the app
does: the names, abbreviations and aliases in English, Spanish and Portuguese
from Genesis/Core/Bible/BibleBook.swift, and the number of verses in each
chapter from the bundled KJV (verse ids use the KJV's numbering everywhere).
No verse text is read or written.

    python3 Tools/BibleData/export_reference_books.py          # write
    python3 Tools/BibleData/export_reference_books.py --check  # fail if stale

references.test.ts also fails when the JSON no longer matches BibleBook.swift.
"""
import json
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SWIFT = ROOT / "Genesis/Core/Bible/BibleBook.swift"
KJV = ROOT / "Genesis/Resources/Bibles/KJV.sqlite"
OUT = ROOT / "supabase/functions/_shared/bibleBooks.json"


def strings(text):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', text)


def parse_swift(source):
    books = []
    for m in re.finditer(
        r'\.init\(id: (\d+), osis: "([^"]+)", englishName: "([^"]+)", englishAbbreviation: "([^"]+)", '
        r'testament: \.(old|new), chapterCount: (\d+), aliases: \[([^\]]*)\]\)',
        source,
    ):
        books.append({
            "id": int(m.group(1)), "osis": m.group(2), "en": {"name": m.group(3), "abbreviation": m.group(4),
                                                               "aliases": strings(m.group(7))},
            "testament": m.group(5), "chapterCount": int(m.group(6)),
        })

    def local(block_name):
        start = source.index(f"static let {block_name}: [LocalName] = [")
        end = source.index("\n    ]", start)
        return [
            {"name": n, "abbreviation": a, "aliases": strings(al)}
            for n, a, al in re.findall(
                r'\.init\(name: "([^"]+)", abbreviation: "([^"]+)", aliases: \[([^\]]*)\]\)', source[start:end])
        ]

    spanish, portuguese = local("spanish"), local("portuguese")
    if not (len(books) == len(spanish) == len(portuguese) == 66):
        sys.exit(f"expected 66 books, found {len(books)}/{len(spanish)}/{len(portuguese)}")
    for book, es, pt in zip(books, spanish, portuguese):
        book["es"], book["pt"] = es, pt
    return books


def verse_counts(book_id, chapters):
    db = sqlite3.connect(f"file:{KJV}?mode=ro", uri=True)
    rows = dict(db.execute("select chapter, max(verse) from verses where book = ? group by chapter", (book_id,)))
    counts = [rows.get(c, 0) for c in range(1, chapters + 1)]
    if 0 in counts:
        sys.exit(f"book {book_id}: a chapter has no verses in the KJV")
    return counts


def build():
    books = parse_swift(SWIFT.read_text(encoding="utf-8"))
    for book in books:
        book["verses"] = verse_counts(book["id"], book["chapterCount"])
    return json.dumps({
        "source": "Generated by Tools/BibleData/export_reference_books.py from BibleBook.swift and the KJV's verse counts. Do not edit.",
        "books": books,
    }, ensure_ascii=False, indent=1) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run {Path(__file__).relative_to(ROOT)}")
        print("bibleBooks.json is current")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

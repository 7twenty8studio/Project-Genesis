#!/usr/bin/env python3
"""Builds the welcome illustrations (Assets.xcassets/Onboarding-*.imageset)
from the originals in Tools/Onboarding/Originals.

The originals were generated by the owner with ChatGPT (OpenAI) and are kept
here untouched. ChatGPT doesn't give real transparency reliably, so this
cleans them up:
- read and together have a checkerboard painted into the pixels (squares
  of ~207 and ~133 gray, ~12 px, sometimes tinted by the picture): it is
  found and cut away;
- listen and pray have a real alpha channel with stray red and yellow
  specks and faint dust around the edges: those are removed.
Then loose islands go, the edge is eased by a pixel so no gray or black
fringe shows, and the picture is trimmed and scaled for @3x.

    python3 Tools/Onboarding/make_onboarding.py

Needs numpy, opencv-python-headless and Pillow.
"""

import json
import os

import cv2
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ORIGINALS = os.path.join(ROOT, "Tools/Onboarding/Originals")
ASSETS = os.path.join(ROOT, "Genesis/Resources/Assets.xcassets")
# name in Originals -> imageset, and whether the background is painted on
PICTURES = {
    "read": ("OnboardingRead", True),
    "listen": ("OnboardingListen", False),
    "pray": ("OnboardingPray", False),
    "together": ("OnboardingTogether", True),
}
LONG_SIDE = 960  # 320 pt at @3x


def painted_checkerboard(rgb):
    r, g, b = (rgb[..., i].astype(int) for i in range(3))
    sat = np.maximum(np.maximum(r, g), b) - np.minimum(np.minimum(r, g), b)
    v = (r + g + b) / 3
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    # gray or bluish (the pictures are all warm)
    neutral = ((sat <= 14) | (b >= r - 2)) & (v > 105) & (v < 240)
    # windows holding both kinds of square, even where they're tinted
    light = ((np.abs(lum - 208) <= 16) & (sat <= 34)).astype(np.float32)
    dark = ((np.abs(lum - 134) <= 14) & (sat <= 30)).astype(np.float32)
    fl, fd = cv2.blur(light, (17, 17)), cv2.blur(dark, (17, 17))
    board = (fl >= 0.2) & (fd >= 0.2) & (fl + fd >= 0.65)
    neutral = (neutral | (board & ((light > 0) | (dark > 0)))).astype(np.uint8)

    count, labels, stats, _ = cv2.connectedComponentsWithStats(neutral, connectivity=4)
    h, w = neutral.shape
    background = np.zeros((h, w), bool)
    for i in range(1, count):
        x, y, ww, hh, area = stats[i]
        if x == 0 or y == 0 or x + ww == w or y + hh == h or area >= 12:
            background |= labels == i

    # grow into the squares left between fine twigs and hair
    candidate = (((np.abs(lum - 208) <= 24) | (np.abs(lum - 134) <= 22)) & (r - b <= 18) & (sat <= 40))
    for _ in range(40):
        grown = cv2.dilate(background.astype(np.uint8), np.ones((3, 3), np.uint8)).astype(bool) & candidate
        if not (grown & ~background).any():
            break
        background |= grown
    return np.where(background, 0, 255).astype(np.uint8)


def without_specks(rgba):
    hsv = cv2.cvtColor(rgba[..., :3], cv2.COLOR_RGB2HSV_FULL).astype(int)
    hue, sat = hsv[..., 0] * 360 / 256, hsv[..., 1]
    alpha = rgba[..., 3].astype(int)
    vivid = (sat > 110) & ((hue < 8) | (hue > 48))  # red and yellow, not the browns
    alpha = np.where(vivid | (alpha < 60), 0, alpha)
    return alpha.astype(np.uint8)


def without_islands(alpha, min_area=1500):
    count, labels, stats, _ = cv2.connectedComponentsWithStats((alpha > 0).astype(np.uint8), connectivity=8)
    keep = stats[:, 4] >= min_area
    keep[0] = False
    return np.where(keep[labels], alpha, 0).astype(np.uint8)


def soft_edge(alpha):
    hard = cv2.erode((alpha > 127).astype(np.uint8), np.ones((3, 3), np.uint8))
    soft = cv2.GaussianBlur(hard.astype(np.float32), (0, 0), 0.8)
    return np.clip(soft * 255, 0, 255).astype(np.uint8)


def main():
    for stem, (imageset, painted) in PICTURES.items():
        rgba = np.array(Image.open(os.path.join(ORIGINALS, f"onboarding-{stem}.png")).convert("RGBA"))
        alpha = painted_checkerboard(rgba[..., :3]) if painted else without_specks(rgba)
        alpha = soft_edge(without_islands(alpha))
        rgb = np.where(alpha[..., None] > 0, rgba[..., :3], 0).astype(np.uint8)
        picture = Image.fromarray(np.dstack([rgb, alpha]))
        picture = picture.crop(picture.getbbox())
        picture.thumbnail((LONG_SIDE, LONG_SIDE), Image.LANCZOS)

        folder = os.path.join(ASSETS, imageset + ".imageset")
        os.makedirs(folder, exist_ok=True)
        picture.save(os.path.join(folder, f"onboarding-{stem}.png"), optimize=True)
        contents = {
            "images": [
                {"idiom": "universal", "scale": "1x"},
                {"idiom": "universal", "scale": "2x"},
                {"filename": f"onboarding-{stem}.png", "idiom": "universal", "scale": "3x"},
            ],
            "info": {"author": "xcode", "version": 1},
        }
        with open(os.path.join(folder, "Contents.json"), "w") as f:
            json.dump(contents, f, indent=2)
            f.write("\n")
        print(imageset, picture.size, os.path.getsize(os.path.join(folder, f"onboarding-{stem}.png")) // 1024, "KB")


if __name__ == "__main__":
    main()

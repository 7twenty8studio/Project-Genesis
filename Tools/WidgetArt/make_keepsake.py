"""Builds the keepsake widget pictures (GenesisWidgets/Keepsake/*.jpg) from
the originals in Tools/WidgetArt/Originals.

The originals were generated by the owner with Canva's AI image generator
(the owner owns them; never Canva library content). They are kept here
untouched, with their C2PA manifests, as the record of where each picture
came from. The widget copies are smaller (widgets have little memory) and
keep the Canva XMP label "AI-generation-source"; resizing necessarily
breaks the C2PA manifest's hash binding, which is why the originals stay.

    python3 Tools/WidgetArt/make_keepsake.py
"""
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ORIGINALS = os.path.join(ROOT, "Tools/WidgetArt/Originals")
OUT = os.path.join(ROOT, "GenesisWidgets/Keepsake")
LONG_SIDE = {"linen": 800}


def main():
    os.makedirs(OUT, exist_ok=True)
    for name in sorted(os.listdir(ORIGINALS)):
        if not name.endswith(".png"):
            continue
        stem = name[:-4]
        im = Image.open(os.path.join(ORIGINALS, name))
        xmp = im.info.get("XML:com.adobe.xmp") or im.info.get("xmp")
        exif = im.getexif()
        rgb = im.convert("RGB")
        side = LONG_SIDE.get(stem.removeprefix("keepsake-"), 1100)
        rgb.thumbnail((side, side), Image.LANCZOS)
        options = dict(quality=82, optimize=True, progressive=True, exif=exif.tobytes())
        if xmp:
            options["xmp"] = xmp.encode() if isinstance(xmp, str) else xmp
        rgb.save(os.path.join(OUT, stem + ".jpg"), **options)
        print(stem, rgb.size)


if __name__ == "__main__":
    main()
